#include <vector>

namespace
{
	void PrintUsage()
	{
		std::printf("%s command line tool %s\n", std::string(aegis::c_EngineName).c_str(),
			std::string(aegis::c_EngineVersion).c_str());
		std::printf("\nUsage:\n  AegisCli <command> [arguments]\n\n");
		std::printf("Commands:\n");
		std::printf("  version                        Print the engine version\n");
		std::printf("  demo <directory>               Write the FeatureTest project (scene + scripts)\n");
		std::printf("  scene <file.aescene>           Validate a scene file\n");
		std::printf("  export <project.aeproj> <dir>   Package the runtime and project for distribution\n");
		std::printf("  commands [url]                 List editor AI commands from a running editor\n");
		std::printf("  call <command> [json] [url]    Invoke an editor AI command\n");
	}

	bool CopyDirectoryRecursive(const aegis::FileSystem::Path& source, const aegis::FileSystem::Path& destination)
	{
		bool success = true;
		for (const auto& entry : aegis::FileSystem::ListDirectory(source, true, true))
		{
			const auto relative = entry.lexically_relative(source);
			const auto target = destination / relative;
			if (aegis::FileSystem::IsDirectory(entry))
			{
				success = aegis::FileSystem::CreateDirectories(target) && success;
			}
			else if (aegis::FileSystem::IsFile(entry))
			{
				success = aegis::FileSystem::CopyFileTo(entry, target) && success;
			}
		}
		return success;
	}

	int ExportProject(const std::string& projectFile, const std::string& outputDirectory)
	{
		aegis::Project project;
		std::string error;
		if (!aegis::Project::Load(aegis::FileSystem::FromUtf8(projectFile), project, &error))
		{
			std::fprintf(stderr, "Export failed: %s\n", error.c_str());
			return 1;
		}

		const auto output = aegis::FileSystem::FromUtf8(outputDirectory);
		if (!aegis::FileSystem::CreateDirectories(output))
		{
			std::fprintf(stderr, "Could not create '%s'\n", outputDirectory.c_str());
			return 1;
		}

		const auto executableDirectory = aegis::FileSystem::GetExecutableDirectory();
		const auto runtimeExecutable = executableDirectory / "AegisRuntime.exe";
		if (!aegis::FileSystem::CopyFileTo(runtimeExecutable, output / "AegisRuntime.exe"))
		{
			std::fprintf(stderr, "Could not copy AegisRuntime.exe from '%s'\n",
				aegis::FileSystem::ToUtf8(executableDirectory).c_str());
			return 1;
		}

		if (!CopyDirectoryRecursive(executableDirectory / "shaders", output / "shaders"))
		{
			std::fprintf(stderr, "Could not copy the compiled shaders\n");
			return 1;
		}

		const auto projectOutput = output / "Project";
		if (!CopyDirectoryRecursive(project.RootDirectory, projectOutput))
		{
			std::fprintf(stderr, "Could not copy the project assets\n");
			return 1;
		}

		const std::string readme =
			"Aegis export\n\n"
			"Run the game with:\n"
			"    AegisRuntime.exe Project/" + project.Name + ".aeproj\n\n"
			"Everything in Project/ is your game data; shaders/ is generated by the engine.\n";
		aegis::FileSystem::WriteTextFile(output / "README.txt", readme);

		std::printf("Exported '%s' to '%s'\n", project.Name.c_str(), outputDirectory.c_str());
		return 0;
	}

	int ValidateScene(const std::string& sceneFile)
	{
		aegis::Scene scene;
		std::string error;
		if (!aegis::SceneSerializer::Load(scene, aegis::FileSystem::FromUtf8(sceneFile), &error))
		{
			std::fprintf(stderr, "Invalid scene: %s\n", error.c_str());
			return 1;
		}
		std::printf("Scene '%s' is valid: %zu entities\n", scene.GetName().c_str(), scene.GetEntityCount());
		return 0;
	}
}

int main(int argc, char** argv)
{
	if (argc < 2)
	{
		PrintUsage();
		return 1;
	}

	aegis::Log::Init("");
	const std::string command = argv[1];
	if (command == "help" || command == "--help" || command == "-h")
	{
		PrintUsage();
		return 0;
	}
	if (command == "version" || command == "--version")
	{
		std::printf("%s %s\n", std::string(aegis::c_EngineName).c_str(),
			std::string(aegis::c_EngineVersion).c_str());
		return 0;
	}
	if (command == "demo")
	{
		const std::string directory = argc > 2 ? argv[2] : "Assets/Projects/FeatureTest";
		std::string error;
		if (!aegis::demo::WriteFeatureProject(aegis::FileSystem::FromUtf8(directory), &error))
		{
			std::fprintf(stderr, "%s\n", error.c_str());
			return 1;
		}
		return 0;
	}
	if (command == "scene" && argc > 2)
	{
		return ValidateScene(argv[2]);
	}
	if (command == "export" && argc > 3)
	{
		return ExportProject(argv[2], argv[3]);
	}

	std::fprintf(stderr, "Unknown command '%s'. Run 'AegisCli help'.\n", command.c_str());
	return 1;
}
